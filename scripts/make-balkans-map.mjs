/**
 * Builds the small Balkans outline map for the stats band (owner brief C2)
 * from Natural Earth 1:50m (public domain, via the world-atlas package),
 * projected once with d3-geo and saved as SVG path strings:
 *   components/ui/balkansMap.ts  →  { NEIGHBOURS, ALBANIA, VIEWBOX }
 * Usage: node scripts/make-balkans-map.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"));
const countries = feature(topo, topo.objects.countries).features;

const NEIGHBOURS = ["Kosovo", "Montenegro", "Serbia", "Macedonia", "Greece", "Bosnia and Herz.", "Croatia", "Bulgaria"];
const pick = (name) => countries.find((c) => c.properties.name === name);

// Frame: western Balkans around Albania
const frame = {
  type: "Feature",
  geometry: { type: "Polygon", coordinates: [[[16.5, 39.2], [16.5, 45.4], [24.2, 45.4], [24.2, 39.2], [16.5, 39.2]]] },
};
const size = 100;
const projection = geoMercator().fitExtent([[2, 2], [size - 2, size - 2]], frame);
const [[x0, y0], [x1, y1]] = geoPath(projection).bounds(frame);
projection.clipExtent([[x0, y0], [x1, y1]]);
// Whole units: at a ~40px icon one unit is 0.4px, so integer coordinates look identical (< 8KB)
const path = geoPath(projection).digits(0);

const neighbours = NEIGHBOURS.map(pick).filter(Boolean).map((f) => path(f)).filter(Boolean).join("");
const albania = path(pick("Albania"));
const viewBox = `${x0.toFixed(1)} ${y0.toFixed(1)} ${(x1 - x0).toFixed(1)} ${(y1 - y0).toFixed(1)}`;

const out = `// Generated by scripts/make-balkans-map.mjs from Natural Earth 1:50m (public domain). Do not edit.
export const VIEWBOX = "${viewBox}";
export const NEIGHBOURS = "${neighbours}";
export const ALBANIA = "${albania}";
`;
writeFileSync("components/ui/balkansMap.ts", out);
console.log(`balkansMap.ts: ${(Buffer.byteLength(out) / 1024).toFixed(1)} KB, viewBox ${viewBox}`);
